#!/usr/bin/env node
// Generator for the curl and aws rule blocks in the pi-permission-system
// config.json (permission.bash). Last match wins, so block order matters.
//
// Usage:
//   node permission-rules.mjs          rewrite the generated blocks in config.json
//   node permission-rules.mjs --check  exit 1 if config.json or the manifest differs from the spec
//   --config <path> and --manifest <path> target other files; unknown flags are rejected
//
// Each block is located by the two hand-edited rules that surround it in
// config.json (`neighbors.before` / `neighbors.after`, outside the generated
// set). Every rule strictly between them is replaced by the generated block;
// every other rule keeps its value and position.
// The generator records the keys it wrote, per block and in order, in the
// manifest permission-rules.lock.json next to this file (commit it). Before
// writing anything it checks that every rule between a block's neighbors is
// listed in that block's manifest entry or generated by the current spec;
// otherwise it throws, names the keys and writes nothing. Hand-written rules
// inside a span are never deleted, even if they look generated but are not in
// the spec. A stale manifest (missing keys the spec generates) therefore
// heals on the next write run, but only for a key the spec generates that is
// not in the manifest if its current value equals the generated one; a
// hand-written rule with a different value is refused (it would be silently
// overwritten, possibly loosening a deny). Manifest keys missing from
// config.json (deleted by hand) are fine and reported, unless the spec no
// longer generates them. After a successful write the manifest is
// rewritten to the new generated keys; config.json is written first, each file
// via a temp file and rename. `--check` also fails if the manifest differs from
// the generated keys. A missing manifest is created only if config.json
// already matches the spec. If a neighbor is renamed, moved or duplicated,
// update the spec to match. Hand-written rules must live outside the spans.

import { randomBytes } from "node:crypto";
import { chmodSync, existsSync, lstatSync, readFileSync, readlinkSync, realpathSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { isDeepStrictEqual } from "node:util";

export const CONFIG_PATH = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../extensions/pi-permission-system/config.json",
);

export const LOCK_PATH = resolve(dirname(fileURLToPath(import.meta.url)), "permission-rules.lock.json");

const BLOCKED_PIPE =
  "Blocked by policy. Do not attempt this another way. List it under 'Needs approval' in your final report.";

export const spec = {
  curl: {
    neighbors: { before: "rsync *", after: "wget --post-data*" },
    // Command prefixes. `pipeDeny` also emits `<prefix> * | bash` / `| sh` denies.
    prefixes: [
      { prefix: "curl" },
      { prefix: "*/curl", pipeDeny: true },
      { prefix: "command curl", pipeDeny: true },
      { prefix: "\\curl", pipeDeny: true },
    ],
    // Each flag yields `<prefix> * <flag>*` and `<prefix> <flag>*`. Every
    // single-letter flag also yields bundled-short-flag copies
    // (`-?X*`, `-??X*`, ... up to bundleWidth `?`s) in both forms.
    // Groups are emitted in order, per prefix.
    groups: [
      { flags: ["-X", "-d", "--data", "--request", "-F", "--form", "-T", "--upload-file"] },
      { flags: ["--json"], pipeDenies: true },
      { flags: ["-K", "--config"] },
    ],
    bundleWidth: 8,
    action: "ask",
    pipeDenyShells: ["bash", "sh"],
    pipeDenyRule: { action: "deny", reason: BLOCKED_PIPE },
  },
  aws: {
    neighbors: { before: "gh repo view *", after: "aws s3api *" },
    leadingAllows: ["aws s3 ls *", "aws sts get-caller-identity*"],
    services: [
      "ec2", "iam", "eks", "ecr", "ecs", "cloudformation", "logs", "cloudwatch",
      "lambda", "rds", "route53", "elbv2", "sqs", "sns", "dynamodb", "ssm", "kms",
      "autoscaling", "organizations",
    ],
    readVerbs: ["describe", "list", "get"],
  },
};

// Each generator returns an ordered array of [pattern, rule] entries.
export function generateCurl(c = spec.curl) {
  const out = [];
  for (const { prefix, pipeDeny } of c.prefixes) {
    for (const group of c.groups) {
      for (const flag of group.flags) {
        out.push([`${prefix} * ${flag}*`, c.action], [`${prefix} ${flag}*`, c.action]);
      }
      for (const flag of group.flags) {
        const m = /^-([A-Za-z])$/.exec(flag);
        if (!m) continue;
        for (let w = 1; w <= c.bundleWidth; w++) {
          const bundled = `-${"?".repeat(w)}${m[1]}*`;
          out.push([`${prefix} ${bundled}`, c.action], [`${prefix} * ${bundled}`, c.action]);
        }
      }
      if (group.pipeDenies && pipeDeny) {
        for (const sh of c.pipeDenyShells) out.push([`${prefix} * | ${sh}`, { ...c.pipeDenyRule }]);
      }
    }
  }
  return out;
}

export function generateAws(a = spec.aws) {
  const out = a.leadingAllows.map((p) => [p, "allow"]);
  for (const svc of a.services) {
    for (const verb of a.readVerbs) out.push([`aws ${svc} ${verb}-*`, "allow"]);
  }
  return out;
}

const isPlainObject = (v) => v !== null && typeof v === "object" && !Array.isArray(v);

// Returns the [start, end] indices of the `before` and `after` neighbor rules.
// Throws unless each occurs exactly once and `before` precedes `after`.
export function locateBlock(entries, neighbors, name) {
  const find = (key, role) => {
    const idx = entries.flatMap(([k], i) => (k === key ? [i] : []));
    if (idx.length !== 1) {
      throw new Error(`${name}: ${role} neighbor rule "${key}" found ${idx.length} times in config, expected 1`);
    }
    return idx[0];
  };
  const start = find(neighbors.before, "before");
  const end = find(neighbors.after, "after");
  if (end < start) throw new Error(`${name}: neighbor rules are out of order in config`);
  return { start, end };
}

// Throws, naming every offending key, if an entry strictly inside the span is
// not in `allowed` (the keys the generator wrote last time).
function assertAllowed(entries, { start, end }, allowed, name) {
  const ok = new Set(allowed);
  const bad = entries.slice(start + 1, end).filter(([k]) => !ok.has(k)).map(([k]) => k);
  if (bad.length) {
    throw new Error(
      `${name}: refusing to delete ${bad.length} rule(s) between the neighbor rules that the generator did not write ` +
        `(not in the manifest; move hand-written rules outside the span, or fix the neighbors in the spec): ` +
        bad.map((k) => JSON.stringify(k)).join(", "),
    );
  }
}

function assertUnique(entries, name) {
  const keys = new Set();
  for (const [k] of entries) {
    if (keys.has(k)) throw new Error(`${name}: duplicate rule "${k}" after generation`);
    keys.add(k);
  }
}

// Replaces the entries strictly between the `before` and `after` neighbor
// rules with `generated`. Throws unless each neighbor occurs exactly once and
// `before` precedes `after`, if `allowed` (array of keys) is given and any
// entry being replaced is not in it, or if the result would contain a
// duplicate rule.
export function replaceBlock(entries, generated, neighbors, name, allowed) {
  const span = locateBlock(entries, neighbors, name);
  if (allowed) assertAllowed(entries, span, allowed, name);
  const next = [...entries.slice(0, span.start + 1), ...generated, ...entries.slice(span.end)];
  assertUnique(next, name);
  return next;
}

// The keys the generator writes for `s`, per block, in order.
export function generatedManifest(s = spec) {
  return {
    curl: generateCurl(s.curl).map(([k]) => k),
    aws: generateAws(s.aws).map(([k]) => k),
  };
}

export function parseManifest(text, path) {
  let m;
  try {
    m = JSON.parse(text);
  } catch (err) {
    throw new Error(`${path}: invalid JSON: ${err.message}`);
  }
  for (const name of ["curl", "aws"]) {
    if (!isPlainObject(m) || !Array.isArray(m[name]) || !m[name].every((k) => typeof k === "string")) {
      throw new Error(`${path}: manifest must be {"curl": [keys], "aws": [keys]}`);
    }
  }
  return { curl: m.curl, aws: m.aws };
}

export const serializeManifest = (m) => JSON.stringify({ curl: m.curl, aws: m.aws }, null, 2) + "\n";

// Pure. Returns { config, manifest, missing }: a new config object with both
// blocks regenerated from `s`, the keys generated, and per block the manifest
// keys that are no longer between the neighbors. Both blocks are located and
// validated against the original entries before anything is spliced, so a
// failure never leaves a partial result.
export function planSpec(config, s = spec, manifest) {
  const bash = config?.permission?.bash;
  if (!isPlainObject(bash)) throw new Error("config: permission.bash is missing or not an object");
  const intKeys = Object.keys(bash).filter((k) => /^\d+$/.test(k));
  if (intKeys.length) {
    throw new Error(
      `config: integer-like bash keys would be reordered by JSON objects: ${intKeys.map((k) => JSON.stringify(k)).join(", ")}`,
    );
  }
  if (!manifest) throw new Error("manifest is required");
  const entries = Object.entries(bash);
  const gen = generatedManifest(s);
  const blocks = [
    { name: "curl", neighbors: s.curl.neighbors, generated: generateCurl(s.curl) },
    { name: "aws", neighbors: s.aws.neighbors, generated: generateAws(s.aws) },
  ];
  for (const b of blocks) b.span = locateBlock(entries, b.neighbors, b.name);
  const [x, y] = blocks;
  if (x.span.start < y.span.end && y.span.start < x.span.end) {
    throw new Error(`${x.name} and ${y.name} blocks overlap in config (neighbor spans intersect)`);
  }
  const missing = {};
  for (const b of blocks) {
    // Keys the spec generates are overwritten anyway, so they are always safe
    // to replace; this lets a stale manifest self-heal.
    assertAllowed(entries, b.span, [...manifest[b.name], ...gen[b.name]], b.name);
    // A key that is generated but not in the manifest may be a hand-written
    // rule; healing it is only safe if overwriting does not change its value.
    const stored = new Set(manifest[b.name]);
    const wanted = new Map(b.generated);
    const clashes = entries
      .slice(b.span.start + 1, b.span.end)
      .filter(([k, v]) => !stored.has(k) && wanted.has(k) && !isDeepStrictEqual(v, wanted.get(k)));
    if (clashes.length) {
      throw new Error(
        `${b.name}: refusing to overwrite ${clashes.length} hand-written rule(s) between the neighbor rules whose key the spec generates with a different value ` +
          `(not in the manifest; move them outside the span or change the spec): ` +
          clashes.map(([k, v]) => `${JSON.stringify(k)} is ${JSON.stringify(v)}, generated ${JSON.stringify(wanted.get(k))}`).join("; "),
      );
    }
    const present = new Set(entries.slice(b.span.start + 1, b.span.end).map(([k]) => k));
    const generatedKeys = new Set(gen[b.name]);
    missing[b.name] = manifest[b.name].filter((k) => !present.has(k) && generatedKeys.has(k));
  }
  // Splice from the end so earlier indices stay valid.
  let next = entries;
  for (const b of [...blocks].sort((p, q) => q.span.start - p.span.start)) {
    next = [...next.slice(0, b.span.start + 1), ...b.generated, ...next.slice(b.span.end)];
  }
  assertUnique(next, "config");
  return {
    config: { ...config, permission: { ...config.permission, bash: Object.fromEntries(next) } },
    manifest: gen,
    missing,
  };
}

export const applySpec = (config, s = spec, manifest) => planSpec(config, s, manifest).config;

export const serialize = (config) => JSON.stringify(config, null, 2) + "\n";

// Writes via a temp file in the same directory, then renames over `path`, so
// a crash mid-write never leaves a truncated file. A symlink is followed and
// its target replaced (a dangling one is written at its link target); an
// existing file's mode is preserved.
function resolveTarget(path, depth = 0) {
  if (existsSync(path)) return realpathSync(path);
  if (!lstatSync(path, { throwIfNoEntry: false })?.isSymbolicLink()) return path;
  if (depth > 40) throw new Error(`${path}: too many levels of symbolic links`);
  let link;
  try {
    link = readlinkSync(path);
  } catch (err) {
    throw new Error(`${path}: dangling symlink cannot be resolved: ${err.message}`);
  }
  // Resolve against the real parent: a symlinked parent plus `..` in the link
  // would otherwise be resolved lexically, to the wrong directory.
  return resolveTarget(resolve(realpathSync(dirname(path)), link), depth + 1);
}

export function writeFileAtomic(path, text) {
  const target = resolveTarget(path);
  const mode = existsSync(target) ? statSync(target).mode & 0o7777 : undefined;
  const tmp = `${target}.${process.pid}.${randomBytes(6).toString("hex")}.tmp`;
  try {
    writeFileSync(tmp, text, { flag: "wx", ...(mode !== undefined && { mode }) });
    // The umask may have dropped bits from `mode`; restore it exactly.
    if (mode !== undefined) chmodSync(tmp, mode);
    renameSync(tmp, target);
  } catch (err) {
    rmSync(tmp, { force: true });
    throw err;
  }
}

export function parseConfig(text, path) {
  try {
    return JSON.parse(text);
  } catch (err) {
    throw new Error(`${path}: invalid JSON: ${err.message}`);
  }
}

export function main(argv, s = spec, log = console.log) {
  let check = false;
  let configArg;
  let manifestArg;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--check") check = true;
    else if (a === "--config" || a === "--manifest") {
      const v = argv[++i];
      if (v === undefined || v === "" || v.startsWith("-")) throw new Error(`${a} requires a path`);
      if (a === "--config") configArg = resolve(v);
      else manifestArg = resolve(v);
    } else throw new Error(`unknown argument ${JSON.stringify(a)}; usage: [--check] [--config <path>] [--manifest <path>]`);
  }
  const path = configArg ?? CONFIG_PATH;
  // With --config the manifest defaults to the config's directory so a test
  // copy never touches the committed manifest.
  const lockPath = manifestArg ?? (configArg ? join(dirname(configArg), "permission-rules.lock.json") : LOCK_PATH);
  const current = readFileSync(path, "utf8");
  const config = parseConfig(current, path);
  const stored = existsSync(lockPath) ? parseManifest(readFileSync(lockPath, "utf8"), lockPath) : null;

  let plan;
  if (stored) {
    plan = planSpec(config, s, stored);
  } else {
    // Bootstrap: trust the current span only if config.json already matches the spec.
    plan = planSpec(config, s, generatedManifest(s));
    if (serialize(plan.config) !== current) {
      throw new Error(
        `${lockPath}: manifest is missing and config.json does not match the spec, so the generated rules cannot be told from hand-written ones; ` +
          "restore the manifest from version control, or fix config.json by hand to match the spec first",
      );
    }
  }
  const next = serialize(plan.config);
  const configOk = next === current;
  const manifestOk = stored !== null && JSON.stringify(stored) === JSON.stringify(plan.manifest);

  if (check) {
    if (configOk && manifestOk) return 0;
    if (!configOk) console.error("config.json differs from permission-rules.mjs spec; run: node pi/.pi/agent/scripts/permission-rules.mjs");
    else console.error(`${lockPath} ${stored ? "differs from the generated keys (manifest stale)" : "is missing"}; run: node pi/.pi/agent/scripts/permission-rules.mjs`);
    return 1;
  }
  for (const [name, keys] of Object.entries(plan.missing)) {
    if (keys.length) log(`note: ${name}: ${keys.length} generated rule(s) were missing from config.json: ${keys.map((k) => JSON.stringify(k)).join(", ")}`);
  }
  if (!configOk) {
    writeFileAtomic(path, next);
    log("config.json rewritten");
  }
  if (!manifestOk) {
    writeFileAtomic(lockPath, serializeManifest(plan.manifest));
    log("manifest written");
  }
  return 0;
}

// Under --preserve-symlinks-main neither side is realpathed, so resolve both.
// If argv[1] is set but either path cannot be resolved, the entry point is
// unconfirmed: fail closed instead of silently skipping main.
function isEntryPoint() {
  if (!process.argv[1]) return false;
  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch (err) {
    console.error(`permission-rules: cannot confirm entry point: ${err.message}`);
    process.exit(1);
  }
}

if (isEntryPoint()) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (err) {
    console.error(`permission-rules: ${err.message}`);
    process.exitCode = 1;
  }
}
